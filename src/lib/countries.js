// Flaga si emoji nga kodi ISO 2-shkronjësh
export function flagFromCode(code) {
  if (!code || String(code).length !== 2) return '🏳️';
  const A = 0x1f1e6;
  try {
    return String.fromCodePoint(
      ...String(code).toUpperCase().split('').map(c => A + c.charCodeAt(0) - 65)
    );
  } catch (e) {
    return '🏳️';
  }
}

