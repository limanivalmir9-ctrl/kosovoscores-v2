// Lookup flag + emër nga vlera e ruajtur (emër ose kod)
export function countryInfo(value) {
  if (!value) return null;
  const v = String(value).trim();
  const byName = COUNTRIES.find(c => c.name.toLowerCase() === v.toLowerCase());
  if (byName) return { code: byName.code, name: byName.name, flag: flagFromCode(byName.code) };
  const byCode = COUNTRIES.find(c => c.code.toLowerCase() === v.toLowerCase());
  if (byCode) return { code: byCode.code, name: byCode.name, flag: flagFromCode(byCode.code) };
  // Vlerë manuale (tekst i lirë) — ktheje pa flamur
  return { code: null, name: v, flag: null };
}